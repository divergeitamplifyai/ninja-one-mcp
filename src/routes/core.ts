const ACTIVITY_COMPACT = ['id', 'deviceId', 'activityTime', 'activityType', 'statusCode', 'status', 'severity', 'subject', 'message'] as const;

function report(tool: string, path: string, op: string, what: string, extra: Record<string, Param> = {}, withDf = true): Route {
  return {
    tool,
    kind: 'read',
    method: 'GET',
    path,
    ops: [op],
    description:
      `Report ${what} across devices, one row per item, cursor paged. ` +
      (withDf ? 'Narrow with df (device filter). ' : '') +
      `Use it for fleet questions; follow up on one device with ${P}_get_device_profile.`,
    scope: withDf ? { kind: 'df' } : { kind: 'unscoped', reason: 'this report has no device or organization filter' },
    params: { ...(withDf ? { df } : {}), ...extra },
    list: { paging: { style: 'cursor' }, items: 'results', maxPage: 1000 },
  };
}


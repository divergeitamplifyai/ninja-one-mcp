#!/usr/bin/env node
// Generates the tool catalog from the BUILT server, so docs never drift from code:
//
//   docs/TOOLS.md        every tool by toolset, with kind and description
//   site/catalog.json    the same data for the website's searchable catalog
//
// Usage: npm run build && node scripts/gen-catalog.mjs [--check]

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { loadConfig } = await import(pathToFileURL(join(ROOT, 'dist/config.js')).href);
const { createServer } = await import(pathToFileURL(join(ROOT, 'dist/server.js')).href);
const { ALL_ROUTES } = await import(pathToFileURL(join(ROOT, 'dist/routes/index.js')).href);
const { TOOLSETS, DEFAULT_TOOLSETS, toolsetForRoute } = await import(pathToFileURL(join(ROOT, 'dist/toolsets.js')).href);
const { SERVER_VERSION } = await import(pathToFileURL(join(ROOT, 'dist/constants.js')).href);

const HANDWRITTEN = {
  ninjaone_status_server: 'core',
  ninjaone_status_gate: 'core',
  ninjaone_test_connection: 'core',
  ninjaone_find_organization: 'core',
  ninjaone_report_fleet_health: 'core',
  ninjaone_get_device_profile: 'devices',
  ninjaone_list_board_tickets: 'ticketing',
  ninjaone_add_ticket_comment: 'ticketing',
  ninjaone_send_ticket_reply: 'ticketing',
  ninjaone_api_get: 'api',
  ninjaone_api_write: 'api',
  ninjaone_view_fleet: 'views',
  ninjaone_view_device: 'views',
  ninjaone_view_alerts: 'views',
};
const toolsetOf = new Map(ALL_ROUTES.map((r) => [`ninjaone_${r.tool}`, toolsetForRoute(r)]));
for (const [k, v] of Object.entries(HANDWRITTEN)) toolsetOf.set(k, v);

const { server, tools } = createServer(loadConfig({ NINJAONE_TOOLSETS: 'all' }));
const registered = server._registeredTools;
const rows = [...tools.entries()].map(([name, kind]) => {
  const t = registered[name];
  return {
    name,
    title: t?.title ?? name,
    kind,
    toolset: toolsetOf.get(name) ?? 'core',
    description: (t?.description ?? '').replace(/\s+/g, ' ').trim(),
  };
});
const missing = rows.filter((r) => !toolsetOf.has(r.name)).map((r) => r.name);
if (missing.length) {
  console.error(`No toolset recorded for: ${missing.join(', ')}. Add them to HANDWRITTEN in scripts/gen-catalog.mjs.`);
  process.exit(1);
}
rows.sort((a, b) => a.toolset.localeCompare(b.toolset) || a.name.localeCompare(b.name));

const counts = { total: rows.length, read: 0, write: 0, destructive: 0 };
for (const r of rows) counts[r.kind]++;
const defaultCount = rows.filter((r) => DEFAULT_TOOLSETS.includes(r.toolset)).length;

const catalog = { version: SERVER_VERSION, counts, default_toolsets: DEFAULT_TOOLSETS, default_count: defaultCount, toolsets: TOOLSETS, tools: rows };

const KIND = { read: 'read', write: 'write', destructive: '**destructive**' };
let md = `# Tool catalog\n\nGenerated by \`scripts/gen-catalog.mjs\` from the built server (v${SERVER_VERSION}). Do not edit by hand.\n\n`;
md += `${counts.total} tools: ${counts.read} read, ${counts.write} write, ${counts.destructive} destructive. `;
md += `The default toolsets (${DEFAULT_TOOLSETS.join(', ')}) list ${defaultCount}; set \`NINJAONE_TOOLSETS\` to change that.\n\n`;
md += '| Toolset | Tools | What it covers |\n|---|---|---|\n';
for (const [name, about] of Object.entries(TOOLSETS)) {
  md += `| \`${name}\`${DEFAULT_TOOLSETS.includes(name) ? ' (default)' : ''} | ${rows.filter((r) => r.toolset === name).length} | ${about} |\n`;
}
for (const name of Object.keys(TOOLSETS)) {
  const group = rows.filter((r) => r.toolset === name);
  if (!group.length) continue;
  md += `\n## ${name}\n\n| Tool | Kind | Description |\n|---|---|---|\n`;
  for (const r of group) md += `| \`${r.name}\` | ${KIND[r.kind]} | ${r.description.replace(/\|/g, '\\|')} |\n`;
}

const outputs = [
  [join(ROOT, 'docs/TOOLS.md'), md],
  [join(ROOT, 'site/catalog.json'), JSON.stringify(catalog, null, 1) + '\n'],
];
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([file, text]) => !existsSync(file) || readFileSync(file, 'utf8') !== text).map(([f]) => f.slice(ROOT.length + 1));
  if (stale.length) {
    console.error(`Out of date: ${stale.join(', ')}. Run npm run gen:catalog and commit.`);
    process.exit(1);
  }
  console.log('Tool catalog is current.');
} else {
  for (const [file, text] of outputs) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  console.log(`Catalog: ${counts.total} tools (${counts.read} read, ${counts.write} write, ${counts.destructive} destructive), ${defaultCount} by default.`);
}

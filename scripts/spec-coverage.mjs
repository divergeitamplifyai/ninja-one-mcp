#!/usr/bin/env node
// Maps every operation in spec/ninjaone-public-api-v2.yaml to the tool that
// covers it, and writes docs/api-coverage.md. Fails when an operation is
// unaccounted for, when a route names an operationId the spec does not have,
// or (with --check) when the committed report is stale.
//
// Sources of truth:
//   - ops arrays on declared routes (dist/routes)
//   - HANDWRITTEN below, for tools in src/tools/
//   - "// PASSTHROUGH_ONLY: <operationId>: <reason>" comments in src/routes/*.ts
//
// Usage: npm run build && node scripts/spec-coverage.mjs [--check]

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parse } from 'yaml';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs/api-coverage.md');
const spec = parse(readFileSync(join(ROOT, 'spec/ninjaone-public-api-v2.yaml'), 'utf8'), { maxAliasCount: -1 });
const { ALL_ROUTES } = await import(pathToFileURL(join(ROOT, 'dist/routes/index.js')).href);

const HANDWRITTEN = {
  getTicketsByBoard: 'ninjaone_list_board_tickets',
  createComment: 'ninjaone_add_ticket_comment, ninjaone_send_ticket_reply',
};

const ops = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
    ops.push({ id: op.operationId, method: method.toUpperCase(), path, tag: op.tags?.[0] ?? '-', summary: op.summary ?? '' });
  }
}
const known = new Set(ops.map((o) => o.id));

const covered = new Map();
const problems = [];
for (const route of ALL_ROUTES) {
  for (const id of route.ops) {
    if (!known.has(id)) problems.push(`route ninjaone_${route.tool} names operationId "${id}", which is not in the spec`);
    covered.set(id, [...(covered.get(id) ?? []), `ninjaone_${route.tool}`]);
  }
}
for (const [id, tool] of Object.entries(HANDWRITTEN)) covered.set(id, [...(covered.get(id) ?? []), tool]);

const passthrough = new Map();
const routeDir = join(ROOT, 'src/routes');
for (const file of readdirSync(routeDir)) {
  for (const line of readFileSync(join(routeDir, file), 'utf8').split('\n')) {
    const m = /^\/\/ PASSTHROUGH_ONLY: ([A-Za-z0-9_]+): (.+)$/.exec(line.trim());
    if (m) passthrough.set(m[1], m[2]);
  }
}

const missing = ops.filter((o) => !covered.has(o.id) && !passthrough.has(o.id));
for (const o of missing) problems.push(`${o.method} ${o.path} (${o.id}) is not covered by a tool or listed as PASSTHROUGH_ONLY`);
for (const id of passthrough.keys()) {
  if (!known.has(id)) problems.push(`PASSTHROUGH_ONLY names "${id}", which is not in the spec`);
  if (covered.has(id)) problems.push(`${id} is both covered by a tool and listed as PASSTHROUGH_ONLY`);
}

const typed = ops.filter((o) => covered.has(o.id)).length;
let md = '# API coverage\n\n';
md += `Generated by \`scripts/spec-coverage.mjs\` from \`spec/ninjaone-public-api-v2.yaml\` (${spec.info?.title} ${spec.info?.version}). Do not edit by hand.\n\n`;
md += `${ops.length} operations: ${typed} covered by typed tools, ${passthrough.size} reachable through \`ninjaone_api_get\` / \`ninjaone_api_write\` only, ${missing.length} unaccounted for.\n\n`;
if (passthrough.size) {
  md += '## Passthrough only\n\n| Operation | Method and path | Why |\n|---|---|---|\n';
  for (const o of ops.filter((x) => passthrough.has(x.id))) md += `| \`${o.id}\` | \`${o.method} ${o.path}\` | ${passthrough.get(o.id)} |\n`;
  md += '\n';
}
const tags = [...new Set(ops.map((o) => o.tag))].sort();
for (const tag of tags) {
  md += `## ${tag}\n\n| Method and path | Operation | Tool |\n|---|---|---|\n`;
  for (const o of ops.filter((x) => x.tag === tag)) {
    const tool = covered.get(o.id)?.map((t) => `\`${t}\``).join(', ') ?? (passthrough.has(o.id) ? '_passthrough_' : '**none**');
    md += `| \`${o.method} ${o.path}\` | \`${o.id}\` | ${tool} |\n`;
  }
  md += '\n';
}

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== md) problems.push('docs/api-coverage.md is out of date. Run npm run coverage:spec and commit it.');
} else {
  writeFileSync(OUT, md);
}

for (const p of problems) console.error(`FAIL  ${p}`);
console.log(`${ops.length} operations, ${typed} typed, ${passthrough.size} passthrough only, ${missing.length} unaccounted, ${problems.length} problems.`);
process.exit(problems.length === 0 ? 0 : 1);
